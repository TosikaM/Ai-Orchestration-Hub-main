#!/usr/bin/env python3
"""
Renders the content plane from content-src/.

  python scripts/gen-content.py            # render
  python scripts/gen-content.py --check    # fail if any generated file is stale (CI)
  python scripts/gen-content.py --list     # show the template -> target map and exit

Placeholders are {{UPPER_SNAKE}} and resolve against content-src/preamble/<kebab>.md.
Generated files carry a two-line banner placed *after* the YAML frontmatter, so the
frontmatter still starts at byte 0 and every loader and parser sees what it expects.

WHY THIS EXISTS
---------------
The grounding contract appeared in twelve hand-maintained copies in the source design:
in the orchestrator agent's Four Laws, in the analyst's "every finding cited", in the
graph navigator's "never claims a symbol the index does not contain", in the security
agent's evidence bar, in grounding-guard's four-question gate, in the research context's
confidence tags, in the review context's Pre-Report Gate, in the skill-invoker
instructions, in two runtime string constants, in the citation-guard hook, and in one
prompt's Grounding section.

The architecture claimed, as a feature, that this was "one vocabulary, used identically
by three components, so a finding can move between components without translation."
That was true on the day it was written and would have become false the first time
somebody improved one copy. One source, N renders, checked in CI.

MERGE CONFLICTS
---------------
Never resolve a conflict on a generated file by accepting either side. Resolve on the
.tmpl and on content-src/preamble/, regenerate, and stage the result. Accepting one
side's render silently discards the other side's template change — and because the
render looks plausible, review does not catch it.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
SRC = ROOT / "content-src"

BANNER = (
    "<!-- GENERATED by scripts/gen-content.py from {source} — DO NOT EDIT. -->\n"
    "<!-- Edit the .tmpl and the content-src/preamble/ blocks, then re-run the generator. -->\n"
)
PLACEHOLDER = re.compile(r"\{\{([A-Z0-9_]+)\}\}")

# A slash command and its prompt-library twin are the same document. The command file is
# what Claude Code dispatches on; the .prompt.md copy is what syncs into a consumer
# repo's .github/prompts/ for people browsing the library. Authoring them separately
# would guarantee they drift, which is the exact failure this generator exists to stop.
MIRRORS = [
    {
        "from_dir": "commands",
        "to_dir": "prompts",
        "rename": lambda stem: f"{stem}.prompt.md",
        "why": "slash command and prompt-library entry are one document",
    },
]


def load_preamble() -> dict:
    blocks = {}
    preamble_dir = SRC / "preamble"
    if not preamble_dir.is_dir():
        return blocks
    for path in sorted(preamble_dir.glob("*.md")):
        key = path.stem.upper().replace("-", "_")
        blocks[key] = path.read_text(encoding="utf-8").strip()
    return blocks


def render(template: Path, blocks: dict) -> tuple:
    text = template.read_text(encoding="utf-8")
    missing = []

    def substitute(match):
        key = match.group(1)
        if key not in blocks:
            missing.append(key)
            return match.group(0)
        return blocks[key]

    body = PLACEHOLDER.sub(substitute, text)
    rel = template.relative_to(ROOT).as_posix()

    # Frontmatter must stay first. Insert the banner after the closing --- so that the
    # YAML parsers in validate-structure.py, in the platform's skill discovery, and in
    # the view plane all still see frontmatter at byte 0.
    if body.startswith("---"):
        head, sep, tail = body.partition("\n---\n")
        return f"{head}{sep}{BANNER.format(source=rel)}{tail}", missing
    return BANNER.format(source=rel) + body, missing


def target_for(template: Path) -> Path:
    """content-src/agents/x.agent.md.tmpl -> agents/x.agent.md"""
    return ROOT / template.relative_to(SRC).with_suffix("")


def mirror_targets(target: Path) -> list:
    out = []
    try:
        rel = target.relative_to(ROOT)
    except ValueError:
        return out
    if not rel.parts:
        return out
    top = rel.parts[0]
    for rule in MIRRORS:
        if top != rule["from_dir"]:
            continue
        stem = target.name[: -len(".md")] if target.name.endswith(".md") else target.stem
        out.append(ROOT / rule["to_dir"] / rule["rename"](stem))
    return out


def main() -> int:
    check_only = "--check" in sys.argv
    list_only = "--list" in sys.argv

    blocks = load_preamble()
    if not blocks:
        print("content-src/preamble/ is empty or missing — nothing to substitute.")
        return 1

    templates = sorted(SRC.rglob("*.tmpl"))
    if not templates:
        print("No .tmpl files under content-src/ — nothing to render.")
        return 1

    if list_only:
        for template in templates:
            target = target_for(template)
            print(f"{template.relative_to(ROOT).as_posix():<60} -> {target.relative_to(ROOT).as_posix()}")
            for mirror in mirror_targets(target):
                print(f"{'':<60}    + {mirror.relative_to(ROOT).as_posix()}")
        print(f"\n{len(templates)} templates, {len(blocks)} preamble blocks.")
        return 0

    stale = []
    all_missing = []
    written = 0

    for template in templates:
        target = target_for(template)
        rendered, missing = render(template, blocks)
        all_missing.extend(f"{template.name}: {{{{{k}}}}}" for k in missing)

        for path in [target] + mirror_targets(target):
            if check_only:
                current = path.read_text(encoding="utf-8") if path.exists() else ""
                if current != rendered:
                    stale.append(path.relative_to(ROOT).as_posix())
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(rendered, encoding="utf-8")
                written += 1

    if all_missing:
        print(f"UNRESOLVED PLACEHOLDERS ({len(all_missing)}):")
        for item in sorted(set(all_missing)):
            print(f"  - {item}")
        print("\nEvery {{PLACEHOLDER}} must have a matching content-src/preamble/<kebab>.md file.")
        return 1

    if check_only:
        if stale:
            print(f"STALE GENERATED FILES ({len(stale)}):")
            for item in stale:
                print(f"  - {item}")
            print("\nRun `python scripts/gen-content.py` and commit BOTH the .tmpl and the render.")
            print("NEVER resolve a merge conflict on a generated file by picking a side —")
            print("resolve on the .tmpl, regenerate, stage the result.")
            return 1
        print(f"Checked {len(templates)} templates against {len(blocks)} preamble blocks: in sync.")
        return 0

    print(f"Rendered {written} files from {len(templates)} templates and {len(blocks)} preamble blocks.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
